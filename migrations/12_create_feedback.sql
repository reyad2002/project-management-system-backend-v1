-- 12_create_feedback.sql
-- Client Portal Sprint 3: micro-feedback (1-5 rating on a meeting or phase)

create table feedback (
  id            bigint generated by default as identity primary key,
  company_id    bigint not null references company(id) on delete cascade,
  project_id    bigint not null references projects(id) on delete cascade,
  related_type  varchar(10) not null check (related_type in ('meeting','phase')),
  related_id    bigint not null,
  rating        smallint not null check (rating between 1 and 5),
  submitted_by  bigint not null references client_portal_users(id) on delete cascade,
  created_at    timestamptz not null default now(),

  unique (related_type, related_id, submitted_by)
);

create index idx_feedback_project on feedback(project_id);
