-- 09_create_project_links.sql
-- Client Portal Sprint 1: Project links (staging/live/dashboard URLs shared with the client)

create table project_links (
  id          bigint generated by default as identity primary key,
  company_id  bigint not null references company(id) on delete cascade,
  project_id  bigint not null references projects(id) on delete cascade,
  label       varchar(100) not null,
  url         text not null,
  type        varchar(20) not null default 'other'
    check (type in ('staging','live','dashboard','other')),
  created_by  bigint not null references users(id),
  created_at  timestamptz not null default now()
);

create index idx_project_links_project on project_links(project_id);
