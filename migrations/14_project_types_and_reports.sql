-- 14_project_types_and_reports.sql
-- Project types (software / marketing / branding / social_media / other), a billing model
-- (fixed phases vs monthly retainer vs hybrid) and manual monthly performance reports.
-- Additive only: existing projects become software / fixed.

alter table projects
  add column type text not null default 'software'
    check (type in ('software', 'marketing', 'branding', 'social_media', 'other')),
  add column billing_model text not null default 'fixed'
    check (billing_model in ('fixed', 'retainer', 'hybrid'));

create index idx_projects_company_type on projects(company_id, type);

create table project_reports (
  id                bigint generated by default as identity primary key,
  company_id        bigint not null references company(id) on delete cascade,
  project_id        bigint not null references projects(id) on delete cascade,
  period_month      date not null check (period_month = date_trunc('month', period_month)::date),
  ad_spend          numeric(14, 2) not null default 0 check (ad_spend >= 0),
  reach             integer check (reach >= 0),
  leads             integer check (leads >= 0),
  followers_gained  integer,
  posts_published   integer check (posts_published >= 0),
  summary           text,
  created_by        bigint references users(id) on delete set null,
  created_at        timestamptz not null default now(),
  updated_at        timestamptz not null default now(),

  unique (project_id, period_month)
);

create index idx_project_reports_project on project_reports(project_id, period_month desc);

-- Only the backend (service role) touches this table: RLS on, no client-role grants.
alter table project_reports enable row level security;
revoke all on project_reports from anon, authenticated;
