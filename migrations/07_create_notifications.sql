-- Client Portal Sprint 1: Notifications
-- NOTE: adapted to the live schema (bigint identity PKs, singular `company` table) —
-- the client-portal spec docs show uuid/`companies` examples, do not copy those as-is.

create table notifications (
  id              bigint generated by default as identity primary key,
  company_id      bigint not null references company(id) on delete cascade,
  recipient_type  varchar(20) not null check (recipient_type in ('team_member','client_portal_user')),
  recipient_id    bigint not null,          -- points at users.id or client_portal_users.id depending on recipient_type (no FK, two possible tables)
  type            varchar(40) not null
    check (type in (
      'meeting_reminder','meeting_note_added','action_item_assigned',
      'phase_approved','task_assigned_to_client','feedback_requested','meeting_cancelled'
    )),
  title           varchar(200) not null,
  body            text,
  related_type    varchar(20) check (related_type in ('meeting','task','phase','invoice')),
  related_id      bigint,
  is_read         boolean not null default false,
  read_at         timestamptz,
  created_at      timestamptz not null default now()
);

create index idx_notifications_recipient on notifications(recipient_type, recipient_id, is_read);
create index idx_notifications_company on notifications(company_id);
