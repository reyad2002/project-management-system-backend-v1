-- 11_create_credentials.sql
-- Client Portal Sprint 3: project credentials (encrypted at rest, backend-only encryption)

create table credentials (
  id                  bigint generated by default as identity primary key,
  company_id          bigint not null references company(id) on delete cascade,
  project_id          bigint not null references projects(id) on delete cascade,
  label               varchar(100) not null,
  username            varchar(200) not null,
  password_encrypted  text not null,      -- AES-256-GCM ciphertext ("iv:authTag:ciphertext", base64) — encrypt/decrypt on the backend only, see api/lib/crypto.js
  panel_url           text,
  notes               text,
  created_by          bigint not null references users(id),
  created_at          timestamptz not null default now()
);

create index idx_credentials_project on credentials(project_id);

-- Append-only audit trail: the backend must never UPDATE or DELETE rows here.
create table credential_access_logs (
  id                bigint generated by default as identity primary key,
  credential_id     bigint not null references credentials(id) on delete cascade,
  accessed_by_type  varchar(20) not null check (accessed_by_type in ('team_member','client_portal_user')),
  accessed_by_id    bigint not null,
  accessed_at       timestamptz not null default now()
);

create index idx_credential_access_logs_credential on credential_access_logs(credential_id);
